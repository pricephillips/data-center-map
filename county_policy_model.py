# --------------------------------------------------------------------------
# Selection primitives. Pure functions over coefficient distributions, so the
# rule can be self-tested without fitting anything.
# --------------------------------------------------------------------------

def is_sign_stable(coefs) -> bool:
    """True when every fold agreed on the direction of this variable."""
    cs = list(coefs)
    return bool(cs) and (min(cs) > 0 or max(cs) < 0)


def spec_is_stable(coef_folds: dict) -> bool:
    return all(is_sign_stable(cs) for cs in coef_folds.values())


def instability(coefs) -> float:
    """How evenly a variable's coefficient straddles zero, 0.0 to 1.0.

    0.0 means every fold agreed on the sign. 1.0 means the excursions either
    side of zero are the same size, which is a variable contributing a
    direction it cannot hold. Deliberately a function of the coefficient
    distribution alone: accuracy is not an input, so the elimination path
    cannot be steered toward a better score.
    """
    cs = list(coefs)
    if not cs or is_sign_stable(cs):
        return 0.0
    lo, hi = abs(min(cs)), abs(max(cs))
    if max(lo, hi) == 0:
        return 1.0
    return min(lo, hi) / max(lo, hi)


def least_trustworthy(coef_folds: dict) -> str | None:
    """The variable to eliminate next, or None if all are sign-stable.

    Most evenly straddling zero first; ties broken by the smaller median
    magnitude, so between two equally undecided variables the one
    contributing least is dropped. Both keys are deterministic and the final
    tiebreak is the variable name, so the path does not depend on dict order.
    """
    unstable = {f: cs for f, cs in coef_folds.items() if not is_sign_stable(cs)}
    if not unstable:
        return None
    return min(unstable,
               key=lambda f: (-instability(unstable[f]),
                              abs(st.median(unstable[f])), f))


def choose_admissible(grid: list) -> dict | None:
    """Highest median AUC, then most variables retained, then strongest
    regularization. Applied only to sign-stable candidates."""
    admissible = [g for g in grid if g["sign_stable"]]
    if not admissible:
        return None
    return sorted(admissible,
                  key=lambda g: (-g["auc_median"], -g["n_vars"], g["C"],
                                 g["spec"]))[0]


def stability_cost(grid: list, chosen: dict) -> float:
    """Median AUC given up by requiring sign stability."""
    if not grid:
        return 0.0
    return round(max(g["auc_median"] for g in grid) - chosen["auc_median"], 4)


def spec_diff(previous: list, current: list) -> tuple[list, list]:
    """(entered, left) between two variable sets, both sorted."""
    prev, cur = set(previous or []), set(current or [])
    return sorted(cur - prev), sorted(prev - cur)


def explain_drop(var: str, coefs) -> str:
    """Why a variable left the model, in the evidence that removed it."""
    if coefs is None:
        return f"{var}: not present in the selected specification this run"
    cs = list(coefs)
    if not cs:
        return f"{var}: no coefficient recorded"
    if is_sign_stable(cs):
        return (f"{var}: sign stable but not selected; another specification "
                f"scored higher under the registered criterion")
    return (f"{var}: coefficient changed sign across folds, ranging "
            f"{min(cs):+.4f} to {max(cs):+.4f}, so its direction is not "
            f"supported by the data")


def explain_add(var: str, coefs) -> str:
    """Why a variable entered the model."""
    cs = list(coefs or [])
    if not cs:
        return f"{var}: entered the selected specification"
    direction = "positive" if st.median(cs) > 0 else "negative"
    return (f"{var}: sign stable this run, {direction} in all folds, median "
            f"coefficient {st.median(cs):+.4f}")


HISTORY_FIELDS = ["run_date", "n_counties", "n_positive", "base_rate",
                  "spec", "C", "n_vars", "variables", "entered", "left",
                  "auc_median", "stability_cost", "reasons", "inputs_hash"]


def read_spec_history(path: str = None) -> list:
    """Every recorded specification change, oldest first."""
    try:
        with open(path or SPEC_HISTORY, encoding="utf-8-sig", newline="") as fh:
            return list(csv.DictReader(fh))
    except OSError:
        return []


def append_spec_history(row: dict, path: str = None) -> None:
    """Append-only. One row per change, never per run: a file that grows by a
    row a day whether or not anything moved is a log, not a history, and
    nobody reads it."""
    target = path or SPEC_HISTORY
    os.makedirs(os.path.dirname(target), exist_ok=True)
    exists = os.path.exists(target)
    with open(target, "a", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=HISTORY_FIELDS, lineterminator="\n")
        if not exists:
            w.writeheader()
        w.writerow({k: row.get(k, "") for k in HISTORY_FIELDS})


def dropped_evidence(grid: list, results: dict, var: str):
    """The coefficient folds that explain why a variable is not in the
    selected specification.

    Taken from the widest candidate that still contained it, which is where
    its instability is visible. A variable dropped by elimination shows the
    fit that decided to drop it; one merely not selected shows its last
    stable behaviour, and explain_drop says which case it is.
    """
    holders = [g for g in grid if var in g.get("variables", [])]
    if not holders:
        return None
    widest = max(holders, key=lambda g: (g["n_vars"], -g["C"]))
    res = results.get((widest["spec"], widest["C"]))
    return (res or {}).get("coef_folds", {}).get(var)


def input_hash() -> str:
    """Short hash of the aggregate manifest, so a specification change can be
    traced to the data change that caused it."""
    try:
        with open(MANIFEST, encoding="utf-8") as fh:
            payload = json.load(fh).get("inputs", {})
        return hashlib.sha1(
            json.dumps(payload, sort_keys=True).encode("utf-8")
        ).hexdigest()[:12]
    except (OSError, ValueError):
        return ""


def parse_float(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def transform(name, x):
    if x is None:
        return None
    if name == "log1p":
        return math.log1p(max(x, 0.0))
    if name == "log10":
        return math.log10(x) if x > 0 else None
    return x


def load():
    rows = list(csv.DictReader(open(AGG_CSV, encoding="utf-8-sig")))
    if not rows:
        print("ERROR: empty aggregate; run county_aggregator.py first",
              file=sys.stderr)
        sys.exit(1)
    # Exclude Puerto Rico municipios from the modeling frame: no
    # presidential margin exists, income sits far outside the mainland
    # distribution, and local land-use institutions differ. They remain in
    # the aggregate layer for the map.
    kept = [r for r in rows if not r["fips"].startswith("72")]
    for r in kept:
        m24, m16 = parse_float(r.get("margin_2024")), parse_float(r.get("margin_2016"))
        r["margin_shift"] = ("" if m24 is None or m16 is None
                             else m24 - m16)
    return kept, len(rows) - len(kept)


def main() -> int:
    try:
        import numpy as np
        from sklearn.impute import SimpleImputer
        from sklearn.linear_model import LogisticRegression
        from sklearn.metrics import brier_score_loss, roc_auc_score
        from sklearn.model_selection import RepeatedStratifiedKFold
        from sklearn.pipeline import make_pipeline
        from sklearn.preprocessing import StandardScaler
    except ImportError:
        print("ERROR: scikit-learn required", file=sys.stderr)
        return 1

    rows, n_excluded_pr = load()
    all_feats = [v for v, _, _, _ in VARS]
    tr_by = {v: tr for v, _, _, tr in VARS}
    Xall = np.array(
        [[np.nan if (t := transform(tr, parse_float(r[f]))) is None else t
          for f, _, _, tr in VARS] for r in rows], dtype=float)
    y = np.array([int(r["has_enacted_restrictive"]) for r in rows])
    fips = [r["fips"] for r in rows]
    cv = RepeatedStratifiedKFold(n_splits=N_SPLITS, n_repeats=N_REPEATS,
                                 random_state=SEED)

    def run_cv(feat_list, c_reg):
        ix = [all_feats.index(f) for f in feat_list]
        X = Xall[:, ix]
        aucs, briers = [], []
        coef_folds = {f: [] for f in feat_list}
        oof_sum = np.zeros(len(y))
        oof_cnt = np.zeros(len(y))
        for tr_ix, te_ix in cv.split(X, y):
            pipe = make_pipeline(
                SimpleImputer(strategy="median"),
                StandardScaler(),
                LogisticRegression(C=c_reg, max_iter=4000))
            pipe.fit(X[tr_ix], y[tr_ix])
            p = pipe.predict_proba(X[te_ix])[:, 1]
            aucs.append(roc_auc_score(y[te_ix], p))
            briers.append(brier_score_loss(y[te_ix], p))
            for f, c in zip(feat_list,
                            pipe.named_steps["logisticregression"].coef_[0]):
                coef_folds[f].append(float(c))
            oof_sum[te_ix] += p
            oof_cnt[te_ix] += 1
        stable = all(min(cs) > 0 or max(cs) < 0
                     for cs in coef_folds.values())
        return {"aucs": aucs, "briers": briers, "coef_folds": coef_folds,
                "oof": oof_sum / oof_cnt, "sign_stable": stable}

    # --- candidate search: named anchors plus backward elimination ---
    # The anchors keep the history comparable with the frozen-grid era. The
    # elimination paths are what let a variable leave the model when it stops
    # holding a direction, and rejoin it when it starts holding one again:
    # every path restarts from the full pool on every run, so nothing is
    # permanently excluded by a past run's data.
    grid = []
    results = {}
    feature_sets = {}
    seen = set()

    def evaluate(label, flist, c_reg):
        key = (tuple(sorted(flist)), c_reg)
        if key in seen:
            return None
        seen.add(key)
        res = run_cv(flist, c_reg)
        results[(label, c_reg)] = res
        feature_sets[(label, c_reg)] = list(flist)
        entry = {"spec": label, "C": c_reg, "n_vars": len(flist),
                 "auc_median": round(st.median(res["aucs"]), 4),
                 "sign_stable": res["sign_stable"],
                 "variables": list(flist)}
        grid.append(entry)
        return res

    # Elimination runs from the full pool AND from each registered anchor.
    # Starting only from the full pool made the search greedy in one
    # direction: it can only remove variables that fail the stability rule,
    # so a stable variable that happens to depress accuracy is never
    # reconsidered, and the better stable specification sitting one anchor
    # away is never reached. Starting from every pre-registered anchor fixes
    # that without ever dropping a variable for being inconvenient, which is
    # the line this rule exists to hold.
    starts = [("full_pool", list(all_feats))] + [
        (name, list(flist)) for name, flist in SPECS.items()]

    for c_reg in C_GRID:
        for origin, start in starts:
            working = list(start)
            step = 0
            while len(working) >= MIN_VARS:
                label = origin if step == 0 else f"{origin}_minus{step}"
                res = evaluate(label, working, c_reg)
                if res is None:                 # this set already evaluated
                    res = run_cv(working, c_reg)
                if res["sign_stable"]:
                    break
                drop = least_trustworthy(res["coef_folds"])
                if drop is None:
                    break
                working = [f for f in working if f != drop]
                step += 1

    sel = choose_admissible(grid)
    if sel is None:
        print("ERROR: no sign-stable specification exists at any "
              "regularization strength, including the minimum variable set; "
              "the county layer cannot ship coefficients this run",
              file=sys.stderr)
        return 1
    cost = stability_cost(grid, sel)
    if cost > STABILITY_COST_ALARM:
        print(f"ERROR: the best sign-stable specification gives up "
              f"{cost:.4f} AUC against the best specification overall, "
              f"beyond the registered alarm of {STABILITY_COST_ALARM}. The "
              f"trustworthy model is no longer describing the same "
              f"phenomenon; this needs a look before anything ships.",
              file=sys.stderr)
        return 1
    feats = feature_sets[(sel["spec"], sel["C"])]
    C_REG = sel["C"]
    chosen = results[(sel["spec"], sel["C"])]
    aucs, briers = chosen["aucs"], chosen["briers"]
    coef_folds = chosen["coef_folds"]
    oof = chosen["oof"]

    # calibration: logistic recalibration on pooled out-of-fold predictions.
    # Under strong shrinkage the raw scores are compressed (underconfident),
    # so a recalibration layer is part of the model. To keep the reported
    # calibration honest, recalibrated scores are cross-fitted: each
    # county's calibrated score comes from a recalibration model fit on
    # folds that exclude it.
    eps = 1e-6
    logit_oof = np.log(np.clip(oof, eps, 1 - eps) /
                       np.clip(1 - oof, eps, 1 - eps)).reshape(-1, 1)
    recal = LogisticRegression(C=1e6, max_iter=4000).fit(logit_oof, y)
    cal_slope = float(recal.coef_[0][0])
    cal_intercept = float(recal.intercept_[0])

    from sklearn.model_selection import StratifiedKFold
    oof_cal = np.zeros(len(y))
    for tr_ix, te_ix in StratifiedKFold(n_splits=5, shuffle=True,
                                        random_state=SEED).split(logit_oof, y):
        rc = LogisticRegression(C=1e6, max_iter=4000)
        rc.fit(logit_oof[tr_ix], y[tr_ix])
        oof_cal[te_ix] = rc.predict_proba(logit_oof[te_ix])[:, 1]
    logit_cal = np.log(np.clip(oof_cal, eps, 1 - eps) /
                       np.clip(1 - oof_cal, eps, 1 - eps)).reshape(-1, 1)
    post = LogisticRegression(C=1e6, max_iter=4000).fit(logit_cal, y)
    post_slope = float(post.coef_[0][0])
    post_intercept = float(post.intercept_[0])
    brier_cal = float(np.mean((oof_cal - y) ** 2))

    def pctile(v, q):
        s = sorted(v)
        return s[min(len(s) - 1, int(q * len(s)))]

    # --- specification history: what changed, and the evidence for it ---
    previous = read_spec_history()
    prior_vars = previous[-1]["variables"].split("; ") if previous else []
    entered, left = spec_diff(prior_vars, sorted(feats))
    reasons = ([explain_add(v, coef_folds.get(v)) for v in entered]
               + [explain_drop(v, dropped_evidence(grid, results, v))
                  for v in left])
    changed = bool(entered or left) or not previous
    if changed:
        append_spec_history({
            "run_date": dt.date.today().isoformat(),
            "n_counties": int(len(y)),
            "n_positive": int(y.sum()),
            "base_rate": round(float(y.mean()), 4),
            "spec": sel["spec"],
            "C": C_REG,
            "n_vars": len(feats),
            "variables": "; ".join(sorted(feats)),
            "entered": "; ".join(entered),
            "left": "; ".join(left),
            "auc_median": round(st.median(aucs), 4),
            "stability_cost": cost,
            "reasons": " | ".join(reasons) if reasons
                       else "first recorded specification",
            "inputs_hash": input_hash(),
        })

    base = float(y.mean())
    metrics = {
        "n": int(len(y)),
        "n_excluded_puerto_rico": int(n_excluded_pr),
        "n_positive": int(y.sum()),
        "base_rate": round(base, 4),
        "cv": {"folds": N_SPLITS, "repeats": N_REPEATS, "seed": SEED},
        "specification_selection": {
            "criterion": "sign-stable on all folds; among those, highest "
                         "median AUC, then most variables retained, then "
                         "strongest regularization. Candidates are the named "
                         "anchors plus backward elimination from the full "
                         "variable pool, regenerated from the data on every "
                         "run, so a variable enters when it holds a "
                         "direction and leaves when it stops.",
            "registered": "2026-08-26",
            "selected": {"spec": sel["spec"], "C": C_REG,
                         "variables": feats},
            "stability_cost": cost,
            "stability_cost_note": (
                "median AUC given up by requiring every coefficient to hold "
                "its sign across all folds. Reported, not used as a veto; a "
                "gap beyond " + str(STABILITY_COST_ALARM) + " is a hard "
                "stop."),
            "stability_cost_alarm": STABILITY_COST_ALARM,
            "changed_this_run": changed,
            "entered": entered,
            "left": left,
            "change_reasons": reasons,
            "grid": grid},
        "roc_auc": {"p10": round(pctile(aucs, .10), 4),
                    "p50": round(st.median(aucs), 4),
                    "p90": round(pctile(aucs, .90), 4)},
        "brier": {"p10": round(pctile(briers, .10), 4),
                  "p50": round(st.median(briers), 4),
                  "p90": round(pctile(briers, .90), 4),
                  "base_rate_brier": round(base * (1 - base), 4)},
        "calibration": {
            "raw_slope": round(cal_slope, 3),
            "raw_intercept": round(cal_intercept, 3),
            "post_recalibration_slope": round(post_slope, 3),
            "post_recalibration_intercept": round(post_intercept, 3),
            "brier_calibrated": round(brier_cal, 4),
            "note": "raw scores are compressed by shrinkage; the model "
                    "includes a cross-fitted logistic recalibration layer. "
                    "calibrated_score in the scores file is cross-fitted: "
                    "no county's calibration was fit on itself. Post "
                    "slope near 1 and intercept near 0 indicate the "
                    "calibrated scores are honest probabilities."},
        "coefficients": {
            f: {"min": round(min(cs), 3), "median": round(st.median(cs), 3),
                "max": round(max(cs), 3),
                "sign_stable": bool(min(cs) > 0) or bool(max(cs) < 0)}
            for f, cs in coef_folds.items()},
        "aggregate_manifest": (json.load(open(MANIFEST))
                               if os.path.exists(MANIFEST) else None),
    }

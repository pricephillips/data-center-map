def selftest() -> int:
    """Covers the selection rule, which is the part that decides what ships.

    Deliberately fits nothing: every function under test operates on
    coefficient distributions, so the rule can be checked exactly and in a
    second, without scikit-learn and without the aggregate layer.
    """
    import tempfile
    checks = []

    def check(name, ok):
        checks.append((name, bool(ok)))

    check("all-positive folds are stable", is_sign_stable([0.2, 0.9, 0.4]))
    check("all-negative folds are stable", is_sign_stable([-0.2, -0.9]))
    check("a sign change is not stable", not is_sign_stable([-0.1, 0.3]))
    check("a zero coefficient is not stable", not is_sign_stable([0.0, 0.3]))
    check("no folds is not stable", not is_sign_stable([]))

    check("a stable variable has no instability",
          instability([0.2, 0.9]) == 0.0)
    check("an evenly straddling variable is maximally unstable",
          instability([-0.5, 0.5]) == 1.0)
    check("a barely straddling variable is nearly trustworthy",
          instability([-0.01, 0.9]) < 0.05)
    check("instability ignores magnitude",
          instability([-1.0, 2.0]) == instability([-10.0, 20.0]))

    folds = {"steady": [0.5, 0.6], "wobble": [-0.4, 0.45],
             "nudge": [-0.01, 0.9]}
    check("the most evenly straddling variable goes first",
          least_trustworthy(folds) == "wobble")
    check("a fully stable set eliminates nothing",
          least_trustworthy({"a": [0.1, 0.2]}) is None)
    # Both straddle zero just as evenly, so the tie falls to magnitude and
    # the one contributing less is the one that goes.
    tie = {"big": [-0.5, 0.5, 0.5], "small": [-0.05, 0.05, 0.05]}
    check("equally unstable variables break the tie on magnitude",
          least_trustworthy(tie) == "small")

    grid = [
        {"spec": "unstable_leader", "C": 1.0, "n_vars": 9,
         "auc_median": 0.8074, "sign_stable": False},
        {"spec": "stable_best", "C": 0.1, "n_vars": 7,
         "auc_median": 0.8076, "sign_stable": True},
        {"spec": "stable_smaller", "C": 0.1, "n_vars": 5,
         "auc_median": 0.8076, "sign_stable": True},
        {"spec": "stable_weak", "C": 1.0, "n_vars": 5,
         "auc_median": 0.7944, "sign_stable": True},
    ]
    sel = choose_admissible(grid)
    check("an unstable specification never wins however accurate",
          sel["spec"] != "unstable_leader")
    check("the most accurate stable specification wins",
          sel["auc_median"] == 0.8076)
    check("a tie on accuracy keeps more variables",
          sel["spec"] == "stable_best")
    check("no stable candidate yields no selection",
          choose_admissible([g for g in grid if not g["sign_stable"]]) is None)

    check("stability cost is measured against the whole grid",
          stability_cost(grid, sel) == round(0.8076 - 0.8076, 4))
    check("a stable leader costs nothing",
          stability_cost(grid, grid[1]) == 0.0)
    check("cost is positive when stability loses accuracy",
          stability_cost([grid[0], grid[3]], grid[3]) == 0.013)

    entered, left = spec_diff(["a", "b", "c"], ["b", "c", "d"])
    check("entering variables are detected", entered == ["d"])
    check("leaving variables are detected", left == ["a"])
    check("a first run enters everything",
          spec_diff([], ["a", "b"]) == (["a", "b"], []))
    check("an unchanged specification diffs to nothing",
          spec_diff(["a"], ["a"]) == ([], []))

    # A variable can leave and later rejoin: every run restarts from the full
    # pool, so exclusion is never permanent. This is the property that makes
    # the model adaptive rather than merely shrinking.
    rejoin_in, rejoin_out = spec_diff(["a", "b"], ["a", "b", "c"])
    check("a previously dropped variable can rejoin", rejoin_in == ["c"])

    reason = explain_drop("margin_2024", [-0.112, 0.1263])
    check("a drop reason carries the coefficient range",
          "-0.1120" in reason and "+0.1263" in reason)
    check("a drop reason names the direction problem",
          "direction is not supported" in reason)
    check("a stable-but-unselected variable says so",
          "not selected" in explain_drop("x", [0.4, 0.5]))
    check("an add reason carries the direction",
          "positive" in explain_add("n_projects_tracked", [0.7, 0.8]))
    check("a negative add reason says negative",
          "negative" in explain_add("existing_dc_count", [-0.6, -0.5]))

    with tempfile.TemporaryDirectory() as tmp:
        hist = os.path.join(tmp, "data", "hist.csv")
        check("an absent history reads as empty", read_spec_history(hist) == [])
        append_spec_history({"run_date": "2026-08-26", "spec": "a",
                             "variables": "x; y", "entered": "x; y",
                             "reasons": "first recorded specification"}, hist)
        append_spec_history({"run_date": "2026-09-02", "spec": "b",
                             "variables": "x", "left": "y",
                             "reasons": "y: coefficient changed sign"}, hist)
        rows = read_spec_history(hist)
        check("history is append-only and ordered", len(rows) == 2
              and rows[0]["run_date"] == "2026-08-26")
        check("the header is written once",
              sum(1 for line in open(hist) if line.startswith("run_date")) == 1)
        check("the latest row carries the current variables",
              rows[-1]["variables"] == "x")
        check("every field is present on every row",
              all(set(r) == set(HISTORY_FIELDS) for r in rows))

    failed = [n for n, ok in checks if not ok]
    for n, ok in checks:
        print(f"  {'PASS' if ok else 'FAIL'}  {n}")
    print(f"\n{len(checks) - len(failed)}/{len(checks)} checks passed")
    return 1 if failed else 0


